#!/usr/bin/env python3
"""Build docs/ai/ERP-CODEMAP.md from graphify-out/graph.json.

A compact, deterministic map of the whole ERP for Claude / Codex / Superpowers sessions: read this ONE file instead of crawling
~1,600 files. Stdlib only (no graphify import). Regenerate with scripts/update-codemap.sh (it refreshes the graph first).
"""
import collections
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRAPH = ROOT / "graphify-out" / "graph.json"
OUT = ROOT / "docs" / "ai" / "ERP-CODEMAP.md"
SKIP = ("scripts/vendor", "node_modules", "tmp/", "output/", "outputs/", "graphify-out", ".worktrees")
DEP_RELATIONS = {"calls", "imports", "imports_from", "indirect_call", "references"}
TABLE_RE = re.compile(r"^(erp_\w+|public|acl|auth)\.\w+$")


def skip(path: str) -> bool:
    return (not path) or any(s in path for s in SKIP)


def main() -> int:
    if not GRAPH.exists():
        print("graphify-out/graph.json missing - run: graphify update .", file=sys.stderr)
        return 1
    g = json.loads(GRAPH.read_text(encoding="utf-8"))
    nodes = {n["id"]: n for n in g["nodes"]}
    links = g.get("links") or g.get("edges") or []
    file_of = {nid: (n.get("source_file") or "") for nid, n in nodes.items()}

    # ---- file-level dependency graph (distinct files that use a file) ----
    used_by = collections.defaultdict(set)      # file -> files depending on it
    uses = collections.defaultdict(set)         # file -> files it depends on
    node_deg = collections.Counter()
    for e in links:
        s, t = e.get("source"), e.get("target")
        if s not in nodes or t not in nodes or e.get("relation") not in DEP_RELATIONS:
            continue
        fs, ft = file_of[s], file_of[t]
        node_deg[t] += 1
        if fs and ft and fs != ft and not skip(fs) and not skip(ft):
            used_by[ft].add(fs)
            uses[fs].add(ft)
    syms_in_file = collections.Counter(f for f in file_of.values() if f)

    def short(path: str) -> str:
        return path.replace("supabase/functions/api/", "").replace("frontend/src/", "")

    def domain_of(path: str):
        p = path.split("/")
        if path.startswith("supabase/functions/api/_core/") and len(p) > 5:
            return ("backend", p[4])
        if path.startswith("supabase/functions/api/") and len(p) > 4:
            return ("backend-infra", p[3])
        if path.startswith("frontend/src/pages/dashboard/") and len(p) > 5:
            return ("frontend", p[4] if len(p) > 5 else "(root)")
        if path.startswith("frontend/src/admin/sa"):
            return ("frontend", "SA admin")
        if path.startswith("scripts/") and path.endswith("-guard.mjs"):
            return ("guard", "ci-guards")
        return None

    files = sorted({f for f in file_of.values() if f and not skip(f)})
    by_domain = collections.defaultdict(list)
    for f in files:
        d = domain_of(f)
        if d:
            by_domain[d].append(f)

    out = []
    w = out.append
    commit = g.get("built_at_commit") or ""
    try:
        head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    except Exception:
        head = ""
    w("# PACE ERP - Code Map (auto-generated, read this FIRST)\n")
    w("> Generated by `scripts/build-codemap.py` from the graphify code graph. **Do not edit by hand** - run `scripts/update-codemap.sh`.")
    w(f"> Graph built at commit `{commit[:8]}` - repo HEAD when generated `{head}` - {len(nodes):,} symbols, {len(links):,} links, {len(files):,} source files.")
    w("> Use: find the domain below, open only the 3-6 files it names, then read the real code. For a precise cross-file question run `graphify query \"...\"`, `graphify path A B` or `graphify explain X`.\n")

    w("## 1. Shape of the system\n")
    w("""- **Frontend** `frontend/src` - React + Vite, plain JS (no TypeScript, no shared types with the backend). Pages in `pages/dashboard/<domain>/`, shared grids/forms in `components/`, server calls in `pages/dashboard/*/<domain>Api.js` (one `fetch<Domain>` wrapper per domain), data via `@tanstack/react-query`.
- **Backend** `supabase/functions/api` - one HTTP API (Node/tsx on Render, same code also Deno-checked). Request flow: `_routes/<domain>.routes.ts` -> `_pipeline` (session, company/work-context, ACL) -> `_core/<domain>/*.handlers.ts` -> Supabase (service role). ACL map of every route: `_acl/route-acl-registry.ts`.
- **Database** Supabase Postgres, one schema per area (`erp_procurement`, `erp_inventory`, `erp_production`, `erp_master`, `erp_planning`, `erp_acl`, `erp_menu` ...). Schema change = a file in `supabase/migrations/` (never only via MCP). Stock only moves through `erp_inventory.post_document` / `post_stock_movement`.
- **Access control** is data, not code: capability -> menu -> versioned ACL snapshot. See `docs/Operation Management/PROD-ACL-Access-Decisions.md` and CLAUDE.md bug patterns.
- **CI guards** in `scripts/*-guard.mjs` enforce the recurring bug patterns (company scope, hardcoded roles, payload fields, JSX imports, stock posting ...).
""")

    # ---- backend domains ----
    w("## 2. Backend domains (`supabase/functions/api/_core/<domain>`)\n")
    w("Per domain: files ranked by how many OTHER files depend on them (the real entry points / shared helpers), then what it leans on.\n")
    for (kind, dom), fl in sorted(by_domain.items()):
        if kind != "backend":
            continue
        ranked = sorted(fl, key=lambda f: (-len(used_by[f]), f))
        dep_targets = collections.Counter()
        for f in fl:
            for t in uses[f]:
                if t not in fl:
                    dep_targets[short(t)] += 1
        w(f"### {dom} - {len(fl)} files, {sum(syms_in_file[f] for f in fl):,} symbols")
        w("Core helpers (most depended on inside this domain): " + ", ".join(f"`{Path(f).name}` ({len(used_by[f])})" for f in ranked[:4] if used_by[f]))
        names = sorted(re.sub(r"\.(handlers?|logic|types|utils|shared)?\.?(ts|js)$", lambda m: (" [" + m.group(1) + "]" if m.group(1) in ("logic", "types", "utils", "shared") else ""), Path(f).name) for f in fl)
        w("Files: " + ", ".join(names))
        if dep_targets:
            w("Leans on: " + ", ".join(f"`{t}`" for t, _ in dep_targets.most_common(5)))
        w("")

    # ---- routes ----
    w("## 3. Route files -> handler domains\n")
    for f in files:
        if "/_routes/" in f and f.endswith(".ts"):
            doms = collections.Counter(domain_of(t)[1] for t in uses[f] if domain_of(t) and domain_of(t)[0] == "backend")
            w(f"- `{Path(f).name}` -> " + (", ".join(f"{d}" for d, _ in doms.most_common(6)) or "(no handler imports found)"))
    w("")

    # ---- frontend ----
    w("## 4. Frontend domains (`frontend/src/pages/dashboard/<domain>`)\n")
    for (kind, dom), fl in sorted(by_domain.items()):
        if kind != "frontend":
            continue
        pages = [Path(f).name for f in fl if f.endswith(".jsx")]
        if not pages:
            continue
        ranked = sorted(fl, key=lambda f: (-len(used_by[f]), f))
        w(f"### {dom} - {len(pages)} pages/components")
        api = [Path(f).name for f in ranked if f.endswith("Api.js")]
        if api:
            w("API client: " + ", ".join(f"`{a}`" for a in api[:3]))
        w("Most reused: " + ", ".join(f"`{Path(f).name}` ({len(used_by[f])})" for f in ranked[:6]))
        w("Pages: " + ", ".join(p.replace(".jsx", "") for p in sorted(pages)[:40]) + (f" ... +{len(pages)-40}" if len(pages) > 40 else ""))
        w("")

    # ---- shared hubs ----
    w("## 5. Shared building blocks (most depended-on files - change with care)\n")
    hubs = sorted((f for f in files if len(used_by[f]) > 0), key=lambda f: (-len(used_by[f]), f))[:30]
    for f in hubs:
        w(f"- `{short(f)}` - used by {len(used_by[f])} files")
    w("")

    # ---- database ----
    w("## 6. Database (from migrations)\n")
    tables = [n for n in nodes.values() if TABLE_RE.match(n["label"]) and (n.get("source_file") or "").endswith(".sql")]
    by_schema = collections.defaultdict(list)
    for n in tables:
        by_schema[n["label"].split(".")[0]].append(n)
    code_touch = collections.Counter()
    for e in links:
        if e.get("relation") in ("reads_from", "writes_to", "references") and e.get("target") in nodes:
            code_touch[nodes[e["target"]]["label"]] += 1
    for schema, tl in sorted(by_schema.items()):
        top = sorted({n["label"] for n in tl}, key=lambda l: (-code_touch[l], l))
        w(f"- **{schema}** - {len(top)} objects. Most touched by code: " + ", ".join(f"`{t.split('.')[1]}`" for t in top[:8]))
    w("")

    # ---- recipes ----
    w("## 7. Where to look for common changes\n")
    w("""- **New/changed API route** -> `_routes/<domain>.routes.ts` + `_acl/route-acl-registry.ts` (pattern must match) + handler in `_core/<domain>/` + client fn in `<domain>Api.js`. Run `scripts/route-acl-registry-guard.mjs`.
- **New report page** -> copy an existing one (`IN03`/`SO04`/`PO24` style): `ErpDenseGrid` + `useColumnLayouts` + `TransactionCompanySelector`; add `operationScreens.js` entry + `AppRouter.jsx` route + ACL rollout (versioned, see CLAUDE.md section 8).
- **Stock movement** -> only `erp_inventory.post_document` with a module completion function registered in `posting_source_registry`; never raw `post_stock_movement` in new code.
- **List endpoint with id arrays** -> `fetchInChunks` from `_shared/chunkedIn.ts`, never a raw `.in()` over unbounded ids.
- **Company scope** -> every read/write validates the company (`_shared/companyScope.ts`); single-company users auto-resolve.
- **DB change** -> migration file first, apply, reconcile `schema_migrations`, `NOTIFY pgrst, 'reload schema'`, run `scripts/migration-integrity-check.mjs`.
""")
    w(f"\n---\n_Generated from {len(files):,} files. Source of truth is the code; if this map disagrees with a file you opened, trust the file and re-run `scripts/update-codemap.sh`._")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(out) + "\n"
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)/1024:.1f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
